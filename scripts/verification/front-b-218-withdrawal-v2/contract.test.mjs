import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const { PGlite } = createRequire(import.meta.url)('@electric-sql/pglite');
const guard="DO $guard$ BEGIN RAISE EXCEPTION 'GUARDED: review cutover and exact database provenance'; END $guard$;";
const sql=await readFile(new URL('./guarded.sql.txt',import.meta.url),'utf8');
const a='11111111-1111-4111-8111-111111111111', b='22222222-2222-4222-8222-222222222222';
const sa='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', sb='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
const ia='33333333-3333-4333-8333-333333333333';
const setup=`
CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
CREATE SCHEMA auth; CREATE SCHEMA app_private;
CREATE TABLE auth.users(id uuid primary key);
CREATE TABLE auth.sessions(id uuid primary key,user_id uuid);
CREATE TABLE public.user_moderation(user_id uuid primary key);
CREATE TABLE app_private.user_admission(user_id uuid primary key);
CREATE TABLE app_private.signup_completion_fences_draft(user_id uuid primary key,origin_withdrawn boolean not null default false);
CREATE TABLE app_private.signup_intents(id uuid primary key,user_id uuid,state text,origin jsonb,origin_consent_version text,origin_consented_at timestamptz,expires_at timestamptz);
CREATE TABLE app_private.signup_origins(user_id uuid primary key,origin jsonb,consent_version text,consented_at timestamptz,expires_at timestamptz);
INSERT INTO auth.users VALUES ('${a}'),('${b}'); INSERT INTO auth.sessions VALUES ('${sa}','${a}'),('${sb}','${b}');
INSERT INTO public.user_moderation VALUES ('${a}'),('${b}'); INSERT INTO app_private.user_admission VALUES ('${a}'),('${b}');
INSERT INTO app_private.signup_origins VALUES ('${a}','{"utm_source":"demo"}','v1',now(),now()+interval '1 year');
INSERT INTO app_private.signup_intents VALUES ('${ia}','${b}','bound','{"utm_source":"example"}','v1',now(),now()+interval '30 minutes');
CREATE FUNCTION app_private.draft_withdraw_identity(u uuid,s uuid) RETURNS boolean LANGUAGE sql AS $$ SELECT EXISTS(SELECT 1 FROM auth.sessions WHERE id=s AND user_id=u) $$;
CREATE FUNCTION app_private.draft_withdraw_current(u uuid,s uuid) RETURNS jsonb LANGUAGE plpgsql AS $$ BEGIN
 UPDATE app_private.signup_intents SET origin=NULL,origin_consent_version=NULL,origin_consented_at=NULL WHERE user_id=u AND state='bound' AND origin IS NOT NULL;
 UPDATE app_private.signup_completion_fences_draft SET origin_withdrawn=true WHERE user_id=u;
 DELETE FROM app_private.signup_origins WHERE user_id=u; RETURN jsonb_build_object('status','withdrawn'); END $$;
CREATE FUNCTION app_private.signup_origin_withdraw(uuid,uuid) RETURNS jsonb LANGUAGE sql AS $$ SELECT '{}'::jsonb $$;
CREATE FUNCTION app_private.signup_discard_pending_origin(uuid,uuid,uuid,text) RETURNS jsonb LANGUAGE sql AS $$ SELECT '{}'::jsonb $$;
CREATE FUNCTION app_private.draft_withdraw_origin(uuid,uuid,uuid,text) RETURNS jsonb LANGUAGE sql AS $$ SELECT '{}'::jsonb $$;
CREATE FUNCTION app_private.draft_withdraw_pending_origin(uuid,uuid,uuid,text) RETURNS jsonb LANGUAGE sql AS $$ SELECT '{}'::jsonb $$;
CREATE FUNCTION public.signup_origin_withdraw(uuid,uuid) RETURNS jsonb LANGUAGE sql AS $$ SELECT '{}'::jsonb $$;
CREATE FUNCTION public.signup_fence_withdraw(uuid,uuid) RETURNS jsonb LANGUAGE sql AS $$ SELECT '{}'::jsonb $$;
CREATE FUNCTION public.signup_discard_pending_origin(uuid,uuid,uuid,text) RETURNS jsonb LANGUAGE sql AS $$ SELECT '{}'::jsonb $$;
`;

test('guard is present and revision comparisons refuse stale choices',async()=>{
 assert.equal(sql.split(guard).length,2);
 const db=new PGlite();
 try {
  await db.exec(setup);
  await assert.rejects(db.exec(sql),/GUARDED/);
  await db.exec('ROLLBACK');
  await db.exec(sql.replace(guard,''));
  const one=async(query,params=[]) => (await db.query(query,params)).rows[0].result;
  const status=(user,session)=>one('SELECT public.signup_origin_status_v2($1,$2) result',[user,session]);
  const withdraw=(user,session,rev)=>one('SELECT public.signup_origin_withdraw_v2($1,$2,$3) result',[user,session,rev]);
  const initial=await status(a,sa); assert.equal(initial.status,'active'); assert.match(initial.revision,/^[0-9a-f-]{36}$/);
  assert.deepEqual(Object.keys(initial).sort(),['revision','status']);
  await assert.rejects(status(a,sb),/Unavailable/);
  assert.equal((await withdraw(b,sb,initial.revision)).status,'stale');
  await db.query("UPDATE app_private.signup_origins SET consented_at=clock_timestamp() WHERE user_id=$1",[a]);
  const renewed=await status(a,sa); assert.notEqual(renewed.revision,initial.revision);
  await assert.rejects(db.query('UPDATE app_private.signup_origins SET origin_revision=$1 WHERE user_id=$2',[initial.revision,a]),/Unavailable/);
  assert.equal((await withdraw(a,sa,initial.revision)).status,'stale');
  assert.equal((await status(a,sa)).revision,renewed.revision);
  assert.equal((await withdraw(a,sa,renewed.revision)).status,'withdrawn');
  assert.equal((await withdraw(a,sa,renewed.revision)).status,'absent');
  const pending=await status(b,sb); assert.equal(pending.status,'active');
  await db.query("UPDATE app_private.signup_intents SET origin_consented_at=clock_timestamp() WHERE id=$1",[ia]);
  const newPending=await status(b,sb); assert.notEqual(pending.revision,newPending.revision);
  await assert.rejects(db.query('UPDATE app_private.signup_intents SET origin_revision=$1 WHERE id=$2',[pending.revision,ia]),/Unavailable/);
  assert.equal((await withdraw(b,sb,pending.revision)).status,'stale');
  assert.equal((await withdraw(b,sb,newPending.revision)).status,'withdrawn');
  assert.equal((await status(b,sb)).status,'absent');
  await db.query("INSERT INTO app_private.signup_origins(user_id,origin,consent_version,consented_at,expires_at) VALUES($1,'{}','v1',now(),now()-interval '1 second')",[a]);
  assert.equal((await status(a,sa)).status,'absent');
  assert.equal((await db.query('SELECT count(*)::int AS n FROM app_private.signup_origins WHERE user_id=$1',[a])).rows[0].n,1);
  await db.query("UPDATE app_private.signup_origins SET expires_at=now()+interval '1 day' WHERE user_id=$1",[a]);
  const live=await status(a,sa);
  await db.exec("CREATE OR REPLACE FUNCTION app_private.draft_withdraw_current(u uuid,s uuid) RETURNS jsonb LANGUAGE sql AS $$ SELECT NULL::jsonb $$");
  await assert.rejects(withdraw(a,sa,live.revision),/Unavailable/);
  await assert.rejects(one('SELECT public.signup_origin_withdraw($1,$2) result',[a,sa]),/Unavailable/);
  await assert.rejects(one('SELECT public.signup_fence_withdraw($1,$2) result',[a,sa]),/Unavailable/);
  const permission=await db.query("SELECT has_function_privilege('authenticated','public.signup_origin_withdraw_v2(uuid,uuid,uuid)','EXECUTE') AS allowed");
  assert.equal(permission.rows[0].allowed,false);
 } finally { await db.close(); }
});
